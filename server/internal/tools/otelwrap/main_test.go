package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const fixtureTypes = `package store

import (
	"go.opentelemetry.io/otel/trace"
)

// Wrapped wraps wrapped.
//
//otelwrap:attr id thing.id
type Wrapped struct {
	inner  *wrapped
	tracer trace.Tracer
}

type wrapped struct{}

// notAWrapper has no tracer, so it is skipped.
type notAWrapper struct {
	inner *wrapped
}
`

func writeFixture(t *testing.T, methods string) string {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "types.go"), []byte(fixtureTypes), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "methods.go"), []byte(methods), 0o600))
	return dir
}

func TestGenerate(t *testing.T) {
	t.Parallel()

	dir := writeFixture(t, `package store

import (
	"context"
	tm "time"
)

func (s *wrapped) Get(ctx context.Context, id string, at tm.Time) (string, bool, error) { return "", false, nil }
func (s *wrapped) Delete(ctx context.Context, ids ...string) error { return nil }
func (s *wrapped) unexported(ctx context.Context) error { return nil }
`)
	src, err := generate(dir, "out_gen.go")
	require.NoError(t, err)

	assert.Equal(t, `// Code generated by otelwrap; DO NOT EDIT.

package store

import (
	"context"
	tm "time"

	"go.opentelemetry.io/otel/attribute"
)

func (s *Wrapped) Delete(ctx context.Context, ids ...string) (err error) {
	ctx, end := startSpan(ctx, s.tracer, "Wrapped.Delete", &err)
	defer end()
	return s.inner.Delete(ctx, ids...)
}

func (s *Wrapped) Get(ctx context.Context, id string, at tm.Time) (_ string, _ bool, err error) {
	ctx, end := startSpan(ctx, s.tracer, "Wrapped.Get", &err,
		attribute.String("thing.id", id),
	)
	defer end()
	return s.inner.Get(ctx, id, at)
}
`, string(src))
}

func TestGenerateRejects(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		methods string
		wantErr string
	}{
		{
			name:    "no context",
			methods: "func (s *wrapped) Get(id string) error { return nil }",
			wantErr: "first parameter must be a context.Context",
		},
		{
			name:    "no error result",
			methods: "func (s *wrapped) Get(ctx context.Context) string { return \"\" }",
			wantErr: "last result must be an error",
		},
		{
			name:    "attribute on non-string",
			methods: "func (s *wrapped) Get(ctx context.Context, id int) error { return nil }",
			wantErr: "parameter id has span attribute thing.id but is int, not string",
		},
		{
			name:    "parameter collides",
			methods: "func (s *wrapped) Get(ctx context.Context, end string) error { return nil }",
			wantErr: `parameter "end" collides`,
		},
		{
			name:    "attribute matches no parameter",
			methods: "func (s *wrapped) Get(ctx context.Context, thingID string) error { return nil }",
			wantErr: "//otelwrap:attr id matches no parameter of wrapped",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			dir := writeFixture(t, "package store\n\nimport \"context\"\n\n"+tt.methods+"\n")
			_, err := generate(dir, "out_gen.go")
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.wantErr)
		})
	}
}

func TestImportName(t *testing.T) {
	t.Parallel()

	tests := map[string]string{
		"context":                        "context",
		"go.opentelemetry.io/otel/trace": "trace",
		"github.com/golang-jwt/jwt/v5":   "jwt",
		"gopkg.in/yaml.v3":               "yaml",
		"example.com/vendor":             "vendor",
	}
	for p, want := range tests {
		assert.Equal(t, want, importName(p), p)
	}
}

func TestGenerateSkipsExcludedFiles(t *testing.T) {
	t.Parallel()

	dir := writeFixture(t, `package store

import "context"

func (s *wrapped) Get(ctx context.Context, id string) error { return nil }
`)
	ignored := "//go:build ignore\n\npackage store\n\nimport \"context\"\n\nfunc (s *wrapped) Extra(ctx context.Context) error { return nil }\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "ignored.go"), []byte(ignored), 0o600))

	src, err := generate(dir, "out_gen.go")
	require.NoError(t, err)
	assert.Contains(t, string(src), "Wrapped.Get")
	assert.NotContains(t, string(src), "Extra")
}
